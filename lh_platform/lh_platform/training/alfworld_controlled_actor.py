class AlfWorldControlledActorError(ValueError):
    """Raised when a controlled state or model-policy trace is not trustworthy."""


@dataclass
class _LiveControlledTrajectory:
    branch: AlfWorldBranch
    state_id: str
    traj_uid: str
    observation: Any
    task_description: str
    history: list[G2POActorHistoryStep]
    anchor_tracker: G2POAnchorTracker
    anchor_observation: str
    goal_graph: GoalGraph
    goal_vector: GoalVector
    controlled_start_state_evidence: Mapping[str, Any]
    records: list[TrainingTrajectoryRecord]
    done: bool = False
    won: bool = False
    terminal_reason: str = ""


def collect_controlled_actor_rollout(
    recipe: AlfWorldControlledAliasingRecipe,
    *,
    task: AlfworldTask,
    task_metadata: Mapping[str, Any],
    instruction: str,
    policy: TrainablePolicy,
    branch_factory: BranchFactory,
    artifacts_dir: str | Path,
    actor_awareness_mode: str,
    samples_per_state: int,
    max_episode_steps: int,
    sampling_seed: int,
    task_manifest_sha256: str,
    rollout_config_sha256: str,
    sampling_temperature: float,
) -> AgenticRolloutBatch:
    """Collect a frozen model-policy batch from both verified collision states.

    Prefix actions only reconstruct the preregistered states. Every action after
    the collision is generated by ``policy`` and passed through the pinned G2PO
    response projection. No continuation program from the fixture is consumed.
    """

    if task.task_id != recipe.task_id:
        raise AlfWorldControlledActorError(
            "controlled actor task differs from the preregistered recipe"
        )
    if actor_awareness_mode not in {"none", "oracle_goal_graph"}:
        raise AlfWorldControlledActorError("unsupported actor awareness mode")
    if samples_per_state < 1 or max_episode_steps < 1:
        raise AlfWorldControlledActorError(
            "controlled actor sample count and horizon must be positive"
        )
    if sampling_temperature <= 0:
        raise AlfWorldControlledActorError("controlled actor sampling temperature must be positive")
    if not str(instruction).strip():
        raise AlfWorldControlledActorError("controlled actor instruction is empty")

    protocol = G2POAlfWorldActorProtocol()
    compiler = AlfWorldSubproblemCompiler()
    goal_graph = compiler.compile_task(task_metadata)
    checkpoint_sha256 = policy.checkpoint_sha256
    group_uid = f"controlled-actor:{recipe.recipe_id}:{actor_awareness_mode}:s{sampling_seed}"
    root = Path(artifacts_dir).resolve()
    live: list[_LiveControlledTrajectory] = []
    owned_branches: list[AlfWorldBranch] = []
    initial_state_receipts: list[dict[str, Any]] = []
    generated_samples: list[OnPolicyActionSample] = []
    try:
        for state in recipe.branches:
            for replicate in range(samples_per_state):
                trajectory_root = (
                    root / actor_awareness_mode / state.branch_id / (f"sample-{replicate:03d}")
                )
                branch = branch_factory(task, recipe.seed, trajectory_root)
                owned_branches.append(branch)
                observation = branch.reset()
                task_description = extract_alfworld_task_description(observation.text)
                initial_prompt = protocol.render_prompt(
                    task_description=task_description,
                    current_observation=observation.text,
                    admissible_actions=observation.admissible_actions,
                    history=(),
                )
                tracker = G2POAnchorTracker(initial_actor_prompt=initial_prompt)
                anchor = observation.text
                history: list[G2POActorHistoryStep] = []
                prefix_evidence: list[dict[str, Any]] = []
                prefix = (*recipe.setup_actions, *state.actions)
                if not prefix:
                    raise AlfWorldControlledActorError(
                        "controlled state requires a restore-verified prefix"
                    )
                for action in prefix:
                    if action not in observation.admissible_actions:
                        raise AlfWorldControlledActorError(
                            f"controlled state prefix action is not admissible: {action}"
                        )
                    before = observation
                    result = branch.step(action)
                    if result.done:
                        raise AlfWorldControlledActorError(
                            "controlled state prefix terminated before model policy"
                        )
                    if not isinstance(result.replay_outcome, Mapping):
                        raise AlfWorldControlledActorError(
                            "controlled state prefix lacks verified replay outcome"
                        )
                    replay_outcome = dict(result.replay_outcome)
                    prefix_evidence.append(
                        {
                            "action": action,
                            "state_snapshot_sha256": result.state_snapshot_sha256,
                            "state_snapshot_artifact_path": (result.state_snapshot_artifact_path),
                            "restore_probe_receipt_sha256": (result.restore_receipt_sha256),
                            "restore_probe_receipt_path": result.restore_receipt_path,
                            "verified_replay_outcome": replay_outcome,
                            "verified_replay_outcome_sha256": canonical_sha256(replay_outcome),
                        }
                    )
                    history.append(
                        G2POActorHistoryStep(
                            observation=before.text,
                            environment_action=action,
                        )
                    )
                    observation = result.observation
                    anchor = tracker.project_next(
                        raw_observation=observation.text,
                        admissible_actions=observation.admissible_actions,
                    )
                vector = compiler.project_state(task_metadata, observation.facts)
                projection = goal_state_projection(goal_graph, vector)
                actual_frontier = tuple(projection["active_frontier_ids"])
                if actual_frontier != state.expected_frontier_ids:
                    raise AlfWorldControlledActorError(
                        "reconstructed controlled state frontier differs from recipe: "
                        f"{state.branch_id} expected={state.expected_frontier_ids!r} "
                        f"actual={actual_frontier!r}"
                    )
                traj_uid = f"{group_uid}:{state.branch_id}:r{replicate}"
                live.append(
                    _LiveControlledTrajectory(
                        branch=branch,
                        state_id=state.branch_id,
                        traj_uid=traj_uid,
                        observation=observation,
                        task_description=task_description,
                        history=history,
                        anchor_tracker=tracker,
                        anchor_observation=anchor,
                        goal_graph=goal_graph,
                        goal_vector=vector,
                        controlled_start_state_evidence={
                            "initial_actor_prompt": initial_prompt,
                            "prefix_steps": prefix_evidence,
                        },
                        records=[],
                    )
                )
                initial_state_receipts.append(
                    {
                        "state_id": state.branch_id,
                        "replicate": replicate,
                        "raw_observation": observation.text,
                        "official_anchor": anchor,
                        "admissible_actions": list(observation.admissible_actions),
                        "active_frontier_ids": list(actual_frontier),
                        "prefix": list(prefix),
                    }
                )

        _validate_collision_reconstruction(initial_state_receipts, recipe)
        for step_idx in range(max_episode_steps):
            active = [trajectory for trajectory in live if not trajectory.done]
            if not active:
                break
            contexts = [
                _actor_context(
                    protocol,
                    trajectory,
                    actor_awareness_mode=actor_awareness_mode,
                    remaining_budget=max_episode_steps - step_idx,
                )
                for trajectory in active
            ]
            requests = tuple(
                PolicyActionRequest(
                    traj_uid=trajectory.traj_uid,
                    step_idx=step_idx,
                    prompt_text=context[0],
                    admissible_actions=(),
                    sampling_temperature=sampling_temperature,
                )
                for trajectory, context in zip(active, contexts, strict=True)
            )
            samples = policy.sample_actions(
                requests,
                seed=sampling_seed + step_idx * 100_000,
            )
            if len(samples) != len(active):
                raise AlfWorldControlledActorError(
                    "model policy did not return one sample per controlled branch"
                )
            generated_samples.extend(samples)
            for trajectory, context, _request, sample in zip(
                active,
                contexts,
                requests,
                samples,
                strict=True,
            ):
                if (sample.traj_uid, sample.step_idx) != (
                    trajectory.traj_uid,
                    step_idx,
                ):
                    raise AlfWorldControlledActorError(
                        "model-policy sample key differs from controlled request"
                    )
                before = trajectory.observation
                before_anchor = trajectory.anchor_observation
                response = protocol.project_response(
                    sample.action_text,
                    admissible_actions=before.admissible_actions,
                )
                result = trajectory.branch.step(response.environment_action)
                if not isinstance(result.replay_outcome, Mapping):
                    raise AlfWorldControlledActorError(
                        "controlled model-policy step lacks verified replay outcome"
                    )
                replay_outcome = dict(result.replay_outcome)
                next_vector = compiler.project_state(
                    task_metadata,
                    result.observation.facts,
                    previous=trajectory.goal_vector,
                )
                next_anchor = trajectory.anchor_tracker.project_next(
                    raw_observation=result.observation.text,
                    admissible_actions=result.observation.admissible_actions,
                )
                budget_terminal = step_idx + 1 >= max_episode_steps
                terminal = bool(result.done or budget_terminal)
                trajectory.done = terminal
                trajectory.won = bool(result.won)
                if result.won:
                    trajectory.terminal_reason = "success"
                elif result.done:
                    trajectory.terminal_reason = "environment_done"
                elif budget_terminal:
                    trajectory.terminal_reason = "max_episode_steps"
                actor_prompt, awareness = context
                trajectory.records.append(
                    TrainingTrajectoryRecord(
                        dataset_id=f"controlled-model-policy:{recipe.sha256}",
                        benchmark="alfworld_native",
                        task_id=task.task_id,
                        split=task.split,
                        seed=sampling_seed,
                        traj_uid=trajectory.traj_uid,
                        group_uid=group_uid,
                        step_idx=step_idx,
                        instruction=str(instruction),
                        observation=before_anchor,
                        action_raw=sample.action_text,
                        action_type="text",
                        parsed_action={"command": response.environment_action},
                        next_observation=next_anchor,
                        reward=float(result.reward),
                        terminal=terminal,
                        success=bool(result.won),
                        outcome_evidence={
                            "won": bool(result.won),
                            "environment_done": bool(result.done),
                            "budget_terminal": budget_terminal,
                            "controller": "model_policy",
                        },
                        action_language="en",
                        method_source="on_policy_controlled_state",
                        model_id=policy.component.name,
                        trajectory_length=None,
                        terminal_reason="pending",
                        decision_role="executor",
                        state_snapshot_sha256=result.state_snapshot_sha256,
                        goal_hash=canonical_sha256(task_metadata),
                        remaining_budget=max_episode_steps - step_idx,
                        action_affordance_hash=canonical_sha256(list(before.admissible_actions)),
                        rollout_config_hash=rollout_config_sha256,
                        active=True,
                        action_token_count=len(sample.action_token_ids),
                        prompt_hash=token_ids_sha256(sample.prompt_token_ids),
                        prompt_ids=sample.prompt_token_ids,
                        response_ids=sample.action_token_ids,
                        response_mask=(1,) * len(sample.action_token_ids),
                        response_old_logprobs=sample.old_action_token_log_probs,
                        extra={
                            "remaining_budget_verified": True,
                            "action_affordance_verified": True,
                            "action_token_count_verified": True,
                            "task_manifest_lock_sha256": task_manifest_sha256,
                            "state_snapshot_artifact_sha256": (result.state_snapshot_sha256),
                            "state_snapshot_artifact_path": (result.state_snapshot_artifact_path),
                            # Persisted after the transition for ledger compilation;
                            # this sidecar is never inserted into the actor prompt.
                            "public_transition_sidecar": build_public_inventory_sidecar(
                                PublicTransitionEvidence(
                                    task_id=task.task_id,
                                    event_id=f"{trajectory.traj_uid}:step-{step_idx:04d}",
                                    sequence=step_idx,
                                    action=response.environment_action,
                                    observation=before.text,
                                    next_observation=result.observation.text,
                                    admissible_actions=tuple(before.admissible_actions),
                                    next_admissible_actions=tuple(
                                        result.observation.admissible_actions
                                    ),
                                )
                            ).to_record(),
                            "environment_step_executed": True,
                            "parser_valid": response.is_action_valid,
                            "action_in_admissible_menu": (
                                response.environment_action in before.admissible_actions
                            ),
                            "restore_verified": True,
                            "restore_probe_receipt_sha256": (result.restore_receipt_sha256),
                            "restore_probe_receipt_path": result.restore_receipt_path,
                            "verified_replay_outcome": replay_outcome,
                            "verified_replay_outcome_sha256": canonical_sha256(replay_outcome),
                            "training_reward_projection": ("official_won_binary_0_10"),
                            "alfworld_task_metadata": dict(task_metadata),
                            "alfworld_facts": list(before.facts),
                            "alfworld_next_facts": list(result.observation.facts),
                            "alfworld_raw_observation": before.text,
                            "alfworld_raw_next_observation": result.observation.text,
                            "alfworld_admissible_actions": list(before.admissible_actions),
                            "alfworld_next_admissible_actions": list(
                                result.observation.admissible_actions
                            ),
                            "actor_task_description": trajectory.task_description,
                            "actor_protocol_id": G2PO_ALFWORLD_ACTOR_PROTOCOL_ID,
                            "g2po_source_revision": recipe.source_revision,
                            "official_anchor_projection_verified": True,
                            "anchor_tracker_implementation_sha256": (
                                g2po_anchor_tracker_source_sha256()
                            ),
                            "actor_awareness_mode": actor_awareness_mode,
                            "actor_context_extension_revision": (
                                CONTEXT_EXTENSION_PLACEMENT_REVISION
                                if actor_awareness_mode != "none"
                                else "none"
                            ),
                            "actor_awareness": awareness,
                            "actor_prompt": actor_prompt,
                            "model_response": sample.action_text,
                            "environment_action": response.environment_action,
                            "is_action_valid": response.is_action_valid,
                            "invalid_action_reasons": list(response.invalid_reasons),
                            "sampling_temperature": sample.sampling_temperature,
                            "controlled_state_id": trajectory.state_id,
                            "controlled_recipe_sha256": recipe.sha256,
                            "controlled_collision_verified": True,
                            "controlled_start_state_evidence": (
                                trajectory.controlled_start_state_evidence
                                if step_idx == 0
                                else None
                            ),
                            "continuation_controller": "model_policy",
                            "deterministic_continuation_program_used": False,
                            "reference_plan_consumed_by_collector": False,
                            "horizon_bucket": task.horizon_bucket,
                            "reference_steps": task.reference_steps,
                        },
                    )
                )
                trajectory.history.append(
                    G2POActorHistoryStep(
                        observation=before.text,
                        environment_action=response.environment_action,
                    )
                )
                trajectory.observation = result.observation
                trajectory.anchor_observation = next_anchor
                trajectory.goal_vector = next_vector

        records: list[TrainingTrajectoryRecord] = []
        for trajectory in live:
            if not trajectory.records or not trajectory.done:
                raise AlfWorldControlledActorError(
                    "controlled model-policy trajectory did not reach its horizon"
                )
            length = len(trajectory.records)
            for index, record in enumerate(trajectory.records):
                records.append(
                    replace(
                        record,
                        trajectory_length=length,
                        terminal=index == length - 1,
                        success=trajectory.won,
                        terminal_reason=trajectory.terminal_reason,
                        outcome_evidence={
                            **record.outcome_evidence,
                            "trajectory_won": trajectory.won,
                            "terminal_reason": trajectory.terminal_reason,
                        },
                    )
                )
        if policy.checkpoint_sha256 != checkpoint_sha256:
            raise AlfWorldControlledActorError(
                "policy checkpoint changed during controlled rollout collection"
            )
        samples_by_key = {
            (sample.traj_uid, sample.step_idx): sample for sample in generated_samples
        }
        batch = AgenticRolloutBatch(
            records=tuple(records),
            policy_samples=tuple(
                samples_by_key[(record.traj_uid, record.step_idx)] for record in records
            ),
            task_manifest_sha256=task_manifest_sha256,
            policy_checkpoint_sha256=checkpoint_sha256,
        )
        return batch.validate()
    except AlfWorldControlledAliasingError as error:
        raise AlfWorldControlledActorError(str(error)) from error
    finally:
        for branch in owned_branches:
            try:
                branch.close()
            except Exception:
                # Cleanup is best-effort; preserve the causal collection error.
                pass


def _actor_context(
    protocol: G2POAlfWorldActorProtocol,
    trajectory: _LiveControlledTrajectory,
    *,
    actor_awareness_mode: str,
    remaining_budget: int,
) -> tuple[str, Mapping[str, Any] | None]:
    awareness = None
    context_extension = None
    if actor_awareness_mode != "none":
        projection = project_actor_awareness(
            trajectory.goal_graph,
            trajectory.goal_vector,
            remaining_budget=remaining_budget,
        )
        awareness = asdict(projection)
        context_extension = f"<goal_awareness>{projection.to_json()}</goal_awareness>"
    return (
        protocol.render_prompt(
            task_description=trajectory.task_description,
            current_observation=trajectory.observation.text,
            admissible_actions=trajectory.observation.admissible_actions,
            history=trajectory.history,
            context_extension=context_extension,
        ),
        awareness,
    )


def _validate_collision_reconstruction(
    receipts: list[Mapping[str, Any]],
    recipe: AlfWorldControlledAliasingRecipe,
) -> None:
    expected_count = len(recipe.branches)
    state_ids = {str(row["state_id"]) for row in receipts}
    if state_ids != {branch.branch_id for branch in recipe.branches}:
        raise AlfWorldControlledActorError(
            "controlled actor did not reconstruct every registered state"
        )
    for field in ("raw_observation", "official_anchor", "admissible_actions"):
        if len({canonical_sha256(row[field]) for row in receipts}) != 1:
            raise AlfWorldControlledActorError(f"controlled actor collision changed {field}")
    frontiers = {tuple(row["active_frontier_ids"]) for row in receipts}
    if len(frontiers) != expected_count:
        raise AlfWorldControlledActorError(
            "controlled actor states do not expose distinct frontiers"
        )
