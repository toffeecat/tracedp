class ScienceWorldOfficialError(RuntimeError):
    """Raised when the official ScienceWorld contract cannot be established."""


@dataclass(frozen=True)
class ScienceWorldRuntime:
    """The executable Python/JAR identity used by the upstream API."""

    env_cls: type[Any]
    distribution_version: str
    package_root: Path
    module_path: Path
    jar_path: Path


@dataclass(frozen=True)
class TaskManifest:
    path: Path
    file_sha256: str
    payload: Mapping[str, Any]
    instances: tuple[Mapping[str, Any], ...]


@dataclass(frozen=True)
class LockVerification:
    status: str
    path: Path
    reason: str
    sha256: str | None = None
    payload: Mapping[str, Any] | None = None


@dataclass
class _ActiveTask:
    env: Any
    instance: Mapping[str, Any]
    last_score: int = 0
    last_reward: int = 0
    last_moves: int = 0


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return "sha256:" + digest.hexdigest()


def _read_json_mapping(path: Path, *, label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ScienceWorldOfficialError(
            f"cannot read {label}: {type(error).__name__}: {error}"
        ) from error
    if not isinstance(value, dict):
        raise ScienceWorldOfficialError(f"{label} must be a JSON object")
    return value


def _write_json(path: Path, payload: Mapping[str, Any], *, overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise ScienceWorldOfficialError(f"refusing to overwrite existing artifact: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as handle:
        temporary = Path(handle.name)
        json.dump(payload, handle, indent=2, ensure_ascii=False, sort_keys=True)
        handle.write("\n")
    temporary.replace(path)


def _write_bytes(path: Path, payload: bytes, *, overwrite: bool) -> None:
    """Atomically write an exact reviewed artifact without reformatting it."""

    if path.exists() and not overwrite:
        raise ScienceWorldOfficialError(f"refusing to overwrite existing artifact: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="wb",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as handle:
        temporary = Path(handle.name)
        handle.write(payload)
    temporary.replace(path)


def _safe_relative_path(path: Path, root: Path, *, label: str) -> str:
    if path.is_symlink():
        raise ScienceWorldOfficialError(f"{label} must not be a symlink: {path}")
    try:
        relative = path.resolve().relative_to(root.resolve())
    except ValueError as error:
        raise ScienceWorldOfficialError(
            f"{label} must live under repository root: {path}"
        ) from error
    if not relative.parts or any(part in {"", ".", ".."} for part in relative.parts):
        raise ScienceWorldOfficialError(f"{label} has unsafe repository-relative path: {path}")
    return relative.as_posix()


def _require_sha256(value: Any, *, label: str, prefixed: bool = False) -> str:
    raw = str(value or "")
    expected = raw[7:] if prefixed and raw.startswith("sha256:") else raw
    if (prefixed and not raw.startswith("sha256:")) or not _SHA256_RE.fullmatch(expected):
        format_hint = (
            "sha256:<64 lowercase hex characters>" if prefixed else "64 lowercase hex characters"
        )
        raise ScienceWorldOfficialError(f"{label} must be {format_hint}")
    return raw


def _require_revision(value: Any, *, label: str) -> str:
    raw = str(value or "")
    if not _REVISION_RE.fullmatch(raw):
        raise ScienceWorldOfficialError(
            f"{label} must be a full 40-character lowercase Git revision"
        )
    return raw


def _safe_close(env: Any) -> None:
    try:
        env.close()
    except Exception:
        # Cleanup must not change an already recorded environmental verdict.
        pass


def resolve_scienceworld_runtime() -> ScienceWorldRuntime:
    """Resolve the official package, implementation module, and bundled JAR.

    No fallback simulator is accepted here.  An editable or PyPI installation
    is usable only if both its Python implementation and JAR can be hashed.
    """

    try:
        package = importlib.import_module("scienceworld")
        implementation = importlib.import_module("scienceworld.scienceworld")
        constants = importlib.import_module("scienceworld.constants")
        distribution_version = importlib.metadata.version("scienceworld")
    except Exception as error:
        raise ScienceWorldOfficialError(
            "official ScienceWorld package is unavailable; install the pinned upstream package on the evaluation host: "
            f"{type(error).__name__}: {error}"
        ) from error
    env_cls = getattr(package, "ScienceWorldEnv", None) or getattr(
        implementation, "ScienceWorldEnv", None
    )
    module_file = getattr(implementation, "__file__", None)
    jar_raw = getattr(constants, "JAR_PATH", None)
    package_file = getattr(package, "__file__", None)
    if env_cls is None or not module_file or not jar_raw or not package_file:
        raise ScienceWorldOfficialError(
            "installed scienceworld package lacks ScienceWorldEnv/module/JAR identity"
        )
    package_root = Path(str(package_file)).resolve().parent
    module_path = Path(str(module_file)).resolve()
    jar_path = Path(str(jar_raw)).expanduser().resolve()
    if not module_path.is_file() or not jar_path.is_file():
        raise ScienceWorldOfficialError(
            "installed scienceworld implementation module or bundled JAR is missing"
        )
    try:
        module_path.relative_to(package_root)
        jar_path.relative_to(package_root)
    except ValueError as error:
        raise ScienceWorldOfficialError(
            "ScienceWorld module/JAR must both live under its installed package root"
        ) from error
    return ScienceWorldRuntime(
        env_cls=env_cls,
        distribution_version=str(distribution_version),
        package_root=package_root,
        module_path=module_path,
        jar_path=jar_path,
    )


def environment_identity_payload(
    runtime: ScienceWorldRuntime, *, upstream_revision: str
) -> dict[str, str]:
    """Return the immutable runtime identity a reviewed lock signs."""

    revision = _require_revision(upstream_revision, label="upstream_revision")
    try:
        module_relpath = (
            runtime.module_path.resolve().relative_to(runtime.package_root.resolve()).as_posix()
        )
        jar_relpath = (
            runtime.jar_path.resolve().relative_to(runtime.package_root.resolve()).as_posix()
        )
    except ValueError as error:
        raise ScienceWorldOfficialError(
            "ScienceWorld identity paths escaped package root"
        ) from error
    if not runtime.distribution_version.strip():
        raise ScienceWorldOfficialError("ScienceWorld distribution version is empty")
    return {
        "upstream_repository": UPSTREAM_REPOSITORY,
        "upstream_revision": revision,
        "distribution_name": "scienceworld",
        "distribution_version": runtime.distribution_version,
        "module_relpath": module_relpath,
        "module_sha256": _sha256_file(runtime.module_path),
        "jar_relpath": jar_relpath,
        "jar_sha256": _sha256_file(runtime.jar_path),
    }


def _validate_instance(raw: Any, *, index: int) -> dict[str, Any]:
    if not isinstance(raw, Mapping):
        raise ScienceWorldOfficialError(f"task manifest instance {index} must be an object")
    instance_id = str(raw.get("instance_id") or "")
    task_name = str(raw.get("task_name") or "")
    if not _INSTANCE_ID_RE.fullmatch(instance_id):
        raise ScienceWorldOfficialError(f"task manifest instance {index} has unsafe instance_id")
    if not _TASK_NAME_RE.fullmatch(task_name):
        raise ScienceWorldOfficialError(f"task manifest {instance_id!r} has unsafe task_name")
    variation_idx = raw.get("variation_idx")
    max_steps = raw.get("max_steps")
    initial_moves = raw.get("initial_moves")
    if not isinstance(variation_idx, int) or variation_idx < 0:
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} variation_idx must be a non-negative integer"
        )
    if not isinstance(max_steps, int) or not 1 <= max_steps <= 10_000:
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} max_steps must be within [1, 10000]"
        )
    if (
        isinstance(initial_moves, bool)
        or not isinstance(initial_moves, Integral)
        or not 0 <= int(initial_moves) <= max_steps
    ):
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} initial_moves must be an integer within [0, max_steps]"
        )
    simplification = str(raw.get("simplification_str") or "")
    if "\n" in simplification or "\r" in simplification:
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} simplification_str must be one line"
        )
    task_description = raw.get("task_description")
    initial_observation = raw.get("initial_observation")
    if not isinstance(task_description, str) or not task_description.strip():
        raise ScienceWorldOfficialError(f"task manifest {instance_id!r} has empty task_description")
    if not isinstance(initial_observation, str) or not initial_observation.strip():
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} has empty initial_observation"
        )
    expected_task_hash = _require_sha256(
        raw.get("task_description_sha256"), label=f"{instance_id}.task_description_sha256"
    )
    expected_observation_hash = _require_sha256(
        raw.get("initial_observation_sha256"), label=f"{instance_id}.initial_observation_sha256"
    )
    if expected_task_hash != canonical_sha256(task_description):
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} task_description_sha256 mismatch"
        )
    if expected_observation_hash != canonical_sha256(initial_observation):
        raise ScienceWorldOfficialError(
            f"task manifest {instance_id!r} initial_observation_sha256 mismatch"
        )
    return {
        "instance_id": instance_id,
        "task_name": task_name,
        "variation_idx": variation_idx,
        "simplification_str": simplification,
        "max_steps": max_steps,
        "initial_moves": int(initial_moves),
        "task_description": task_description,
        "task_description_sha256": expected_task_hash,
        "initial_observation": initial_observation,
        "initial_observation_sha256": expected_observation_hash,
    }


def load_scienceworld_task_manifest(path: str | Path) -> TaskManifest:
    """Load a deterministic, public-task-only selected test roster."""

    manifest_path = Path(path).expanduser().resolve()
    if not manifest_path.is_file() or manifest_path.is_symlink():
        raise ScienceWorldOfficialError(
            f"ScienceWorld task manifest is missing or unsafe: {manifest_path}"
        )
    raw = _read_json_mapping(manifest_path, label="ScienceWorld task manifest")
    if raw.get("schema") != SCIENCEWORLD_TASK_MANIFEST_SCHEMA:
        raise ScienceWorldOfficialError("ScienceWorld task manifest schema mismatch")
    declared_artifact_hash = _require_sha256(
        raw.get("artifact_sha256"), label="task manifest artifact_sha256"
    )
    if declared_artifact_hash != canonical_sha256(
        {key: value for key, value in raw.items() if key != "artifact_sha256"}
    ):
        raise ScienceWorldOfficialError("ScienceWorld task manifest artifact_sha256 mismatch")
    if raw.get("upstream_repository") != UPSTREAM_REPOSITORY:
        raise ScienceWorldOfficialError("ScienceWorld task manifest upstream_repository mismatch")
    _require_revision(raw.get("upstream_revision"), label="task manifest upstream_revision")
    if raw.get("distribution_name") != "scienceworld":
        raise ScienceWorldOfficialError("ScienceWorld task manifest distribution_name mismatch")
    if not str(raw.get("distribution_version") or "").strip():
        raise ScienceWorldOfficialError("ScienceWorld task manifest distribution_version is empty")
    _require_sha256(
        raw.get("environment_identity_sha256"), label="task manifest environment_identity_sha256"
    )
    if raw.get("split") != "test":
        raise ScienceWorldOfficialError("ScienceWorld official adapter accepts test split only")
    instances_raw = raw.get("instances")
    if not isinstance(instances_raw, list) or not instances_raw:
        raise ScienceWorldOfficialError(
            "ScienceWorld task manifest requires a non-empty instances list"
        )
    instances = tuple(
        _validate_instance(item, index=index) for index, item in enumerate(instances_raw)
    )
    ids = [str(instance["instance_id"]) for instance in instances]
    if len(ids) != len(set(ids)):
        raise ScienceWorldOfficialError(
            "ScienceWorld task manifest contains duplicate instance_id values"
        )
    return TaskManifest(
        path=manifest_path,
        file_sha256=_sha256_file(manifest_path),
        payload=raw,
        instances=instances,
    )


def repository_environment_lock_path() -> Path:
    return _REPOSITORY_ROOT / _FIXED_LOCK_RELATIVE_PATH


def _repository_head_blob(path: Path) -> bytes | None:
    try:
        relative = path.resolve().relative_to(_REPOSITORY_ROOT.resolve()).as_posix()
    except ValueError:
        return None
    try:
        result = subprocess.run(
            ["git", "-C", str(_REPOSITORY_ROOT), "show", f"HEAD:{relative}"],
            capture_output=True,
            check=False,
        )
    except OSError:
        return None
    return result.stdout if result.returncode == 0 else None


def _read_reviewed_lock() -> LockVerification:
    path = repository_environment_lock_path()
    if not path.is_file() or path.is_symlink():
        return LockVerification(
            "missing", path, "repository-reviewed ScienceWorld environment lock is not installed"
        )
    try:
        local = path.read_bytes()
    except OSError as error:
        return LockVerification(
            "untrusted", path, f"cannot read environment lock: {type(error).__name__}"
        )
    head = _repository_head_blob(path)
    if head is None or head != local:
        return LockVerification(
            "untrusted", path, "environment lock is not identical to the checked-out HEAD blob"
        )
    try:
        raw = _read_json_mapping(path, label="ScienceWorld environment lock")
    except ScienceWorldOfficialError as error:
        return LockVerification("malformed", path, str(error))
    if raw.get("schema") != SCIENCEWORLD_ENVIRONMENT_LOCK_SCHEMA:
        return LockVerification("malformed", path, "ScienceWorld environment lock schema mismatch")
    if raw.get("candidate_only") is True or raw.get("review_status") != "approved":
        return LockVerification(
            "untrusted",
            path,
            "ScienceWorld environment lock is a candidate, not an approved review",
        )
    review = raw.get("review")
    if not isinstance(review, Mapping) or not str(review.get("reviewer") or "").strip():
        return LockVerification(
            "malformed", path, "ScienceWorld environment lock lacks a reviewed reviewer record"
        )
    try:
        upstream_revision = _require_revision(
            raw.get("upstream_revision"),
            label="ScienceWorld environment lock upstream_revision",
        )
        review_revision = _require_revision(
            review.get("source_revision"),
            label="ScienceWorld environment lock review.source_revision",
        )
    except ScienceWorldOfficialError as error:
        return LockVerification("malformed", path, str(error))
    if review_revision != upstream_revision:
        return LockVerification(
            "malformed",
            path,
            "ScienceWorld environment lock review.source_revision does not match upstream_revision",
        )
    expected_source_url = f"{UPSTREAM_REPOSITORY}/tree/{upstream_revision}"
    if review.get("source_url") != expected_source_url:
        return LockVerification(
            "malformed",
            path,
            "ScienceWorld environment lock review.source_url does not match reviewed upstream revision",
        )
    try:
        declared = _require_sha256(
            raw.get("artifact_sha256"), label="environment lock artifact_sha256"
        )
        calculated = canonical_sha256(
            {key: value for key, value in raw.items() if key != "artifact_sha256"}
        )
    except ScienceWorldOfficialError as error:
        return LockVerification("malformed", path, str(error))
    if declared != calculated:
        return LockVerification(
            "malformed", path, "ScienceWorld environment lock artifact_sha256 mismatch"
        )
    return LockVerification(
        "verified", path, "repository-reviewed environment lock verified", declared, raw
    )


def _mismatch(verification: LockVerification, reason: str) -> LockVerification:
    return LockVerification(
        "mismatch", verification.path, reason, verification.sha256, verification.payload
    )


def verify_scienceworld_environment(
    manifest: TaskManifest,
    runtime: ScienceWorldRuntime,
) -> LockVerification:
    """Check the selected manifest and installed official environment together."""

    verification = _read_reviewed_lock()
    if verification.status != "verified" or verification.payload is None:
        return verification
    lock = verification.payload
    try:
        identity = environment_identity_payload(
            runtime,
            upstream_revision=str(manifest.payload["upstream_revision"]),
        )
        manifest_relpath = _safe_relative_path(
            manifest.path, _REPOSITORY_ROOT, label="task manifest"
        )
    except ScienceWorldOfficialError as error:
        return _mismatch(verification, str(error))
    expected = {
        "upstream_repository": UPSTREAM_REPOSITORY,
        "upstream_revision": str(manifest.payload["upstream_revision"]),
        "distribution_name": "scienceworld",
        "distribution_version": runtime.distribution_version,
        "module_relpath": identity["module_relpath"],
        "module_sha256": identity["module_sha256"],
        "jar_relpath": identity["jar_relpath"],
        "jar_sha256": identity["jar_sha256"],
        "environment_identity_sha256": canonical_sha256(identity),
        "task_manifest_relpath": manifest_relpath,
        "task_manifest_sha256": manifest.file_sha256,
        "task_roster_sha256": canonical_sha256(list(manifest.instances)),
        "split": "test",
    }
    for key, value in expected.items():
        if lock.get(key) != value:
            return _mismatch(verification, f"ScienceWorld environment lock mismatch for {key}")
    if (
        manifest.payload.get("environment_identity_sha256")
        != expected["environment_identity_sha256"]
    ):
        return _mismatch(
            verification, "task manifest environment identity does not match installed runtime"
        )
    return verification


def _validate_environment_identity_fields(
    instance: Mapping[str, Any], info: Mapping[str, Any]
) -> None:
    if str(info.get("taskName") or "") != str(instance["task_name"]):
        raise ScienceWorldOfficialError("official environment returned a different taskName")
    if info.get("variationIdx") != instance["variation_idx"]:
        raise ScienceWorldOfficialError("official environment returned a different variationIdx")
    if str(info.get("simplificationStr") or "") != str(instance["simplification_str"]):
        raise ScienceWorldOfficialError(
            "official environment returned a different simplificationStr"
        )


def _validate_environment_info(
    instance: Mapping[str, Any], info: Mapping[str, Any], observation: str
) -> None:
    _validate_environment_identity_fields(instance, info)
    reset_moves = _official_moves(
        info.get("moves"),
        environment_step_limit=int(instance["max_steps"]),
        phase="reset",
    )
    if reset_moves != int(instance["initial_moves"]):
        raise ScienceWorldOfficialError(
            "official environment reset move count drifted from locked manifest"
        )
    task_description = str(info.get("taskDesc") or "")
    if canonical_sha256(task_description) != instance["task_description_sha256"]:
        raise ScienceWorldOfficialError(
            "official environment task description drifted from locked manifest"
        )
    if canonical_sha256(str(observation)) != instance["initial_observation_sha256"]:
        raise ScienceWorldOfficialError(
            "official environment initial observation drifted from locked manifest"
        )


def _official_score(value: Any) -> int:
    """Accept only the upstream wrapper's integer score range [0, 100]."""

    if isinstance(value, bool) or not isinstance(value, Integral):
        raise ScienceWorldOfficialError("official ScienceWorld info.score must be an integer")
    score = int(value)
    if not 0 <= score <= 100:
        raise ScienceWorldOfficialError("official ScienceWorld info.score must be within [0, 100]")
    return score


def _official_moves(
    value: Any,
    *,
    environment_step_limit: int,
    phase: str,
) -> int:
    """Accept only a bounded integer move count from the official wrapper."""

    if isinstance(value, bool) or not isinstance(value, Integral):
        raise ScienceWorldOfficialError(
            f"official ScienceWorld {phase} info.moves must be an integer"
        )
    moves = int(value)
    # ``ScienceWorldEnv`` emits a terminal timeout on the first transition
    # with moves > envStepLimit.  A selected instance may therefore expose at
    # most one overshoot in a normal episode.
    if not 0 <= moves <= environment_step_limit + 1:
        raise ScienceWorldOfficialError(
            f"official ScienceWorld {phase} info.moves is outside the expected environment boundary"
        )
    return moves


def _runner_action_budget(instance: Mapping[str, Any]) -> int:
    """Derive an agent-action budget from the locked official reset state.

    Upstream ``reset()`` performs ``look around`` internally, so it can
    consume one or more environment moves before the policy receives its
    first observation.  Since timeout occurs only when ``moves >
    envStepLimit``, the number of policy actions needed to observe the
    authoritative terminal boundary is ``limit - initial_moves + 1``.  The
    reset count is staged and revalidated rather than assumed to be zero.
    """

    limit = int(instance["max_steps"])
    initial_moves = int(instance["initial_moves"])
    budget = limit - initial_moves + 1
    if budget < 1:
        raise ScienceWorldOfficialError("ScienceWorld reset leaves no valid policy action budget")
    return budget


def _open_test_instance(
    runtime: ScienceWorldRuntime,
    instance: Mapping[str, Any],
    *,
    validate_locked_public_fields: bool,
) -> tuple[Any, str, Mapping[str, Any]]:
    """Start one upstream JVM, verify test membership, and reset the selected task.

    Staging and evaluation share the same official load/reset path.  Their
    only difference is whether the public reset fields already have a locked
    manifest hash to validate.
    """

    env: Any | None = None
    try:
        env = runtime.env_cls(
            taskName=None,
            serverPath=str(runtime.jar_path),
            envStepLimit=int(instance["max_steps"]),
        )
        env.load(
            str(instance["task_name"]),
            variationIdx=0,
            simplificationStr=str(instance["simplification_str"]),
            generateGoldPath=False,
        )
        test_variations = set(env.get_variations_test())
        if int(instance["variation_idx"]) not in test_variations:
            raise ScienceWorldOfficialError(
                f"selected variation {instance['variation_idx']} is not in official test split for {instance['task_name']}"
            )
        env.load(
            str(instance["task_name"]),
            variationIdx=int(instance["variation_idx"]),
            simplificationStr=str(instance["simplification_str"]),
            generateGoldPath=False,
        )
        observation, info = env.reset()
        if not isinstance(info, Mapping):
            raise ScienceWorldOfficialError(
                "official ScienceWorld reset did not return an info mapping"
            )
        if validate_locked_public_fields:
            _validate_environment_info(instance, info, str(observation))
        else:
            _validate_environment_identity_fields(instance, info)
            task_description = str(info.get("taskDesc") or "")
            if not task_description.strip() or not str(observation).strip():
                raise ScienceWorldOfficialError(
                    "official ScienceWorld reset returned empty public task fields"
                )
        return env, str(observation), dict(info)
    except Exception:
        if env is not None:
            _safe_close(env)
        raise


def _load_and_reset_instance(
    runtime: ScienceWorldRuntime, instance: Mapping[str, Any]
) -> tuple[Any, str, Mapping[str, Any]]:
    """Reset an already locked public task through the official API."""

    return _open_test_instance(runtime, instance, validate_locked_public_fields=True)


def _stage_load_and_reset_instance(
    runtime: ScienceWorldRuntime,
    instance: Mapping[str, Any],
) -> tuple[Any, str, Mapping[str, Any]]:
    """Read public reset fields before their hashes exist in a new manifest."""

    return _open_test_instance(runtime, instance, validate_locked_public_fields=False)


def _observation_from_error(error: Exception) -> Observation:
    return Observation(
        content=f"ScienceWorld official environment rejected this task: {type(error).__name__}: {error}",
        is_error=True,
        info={
            "done": True,
            "success": False,
            "continue": False,
            "environment_error": True,
        },
    )


def _manifest_from_roster(
    *,
    roster: Mapping[str, Any],
    runtime: ScienceWorldRuntime,
    upstream_revision: str,
) -> dict[str, Any]:
    if roster.get("schema") != SCIENCEWORLD_ROSTER_INPUT_SCHEMA:
        raise ScienceWorldOfficialError("ScienceWorld roster input schema mismatch")
    if roster.get("split") != "test":
        raise ScienceWorldOfficialError("ScienceWorld staging accepts test roster inputs only")
    raw_instances = roster.get("instances")
    if not isinstance(raw_instances, list) or not raw_instances:
        raise ScienceWorldOfficialError(
            "ScienceWorld roster input requires a non-empty instances list"
        )
    revision = _require_revision(upstream_revision, label="upstream_revision")
    staged: list[dict[str, Any]] = []
    seen: set[str] = set()
    for index, raw in enumerate(raw_instances):
        # Roster input intentionally contains only selection coordinates; the
        # public reset outputs are generated by the official environment.
        if not isinstance(raw, Mapping):
            raise ScienceWorldOfficialError(
                f"ScienceWorld roster instance {index} must be an object"
            )
        provisional = {
            "instance_id": raw.get("instance_id"),
            "task_name": raw.get("task_name"),
            "variation_idx": raw.get("variation_idx"),
            "simplification_str": raw.get("simplification_str", ""),
            "max_steps": raw.get("max_steps"),
            "initial_moves": 0,
            "task_description": "provisional",
            "task_description_sha256": canonical_sha256("provisional"),
            "initial_observation": "provisional",
            "initial_observation_sha256": canonical_sha256("provisional"),
        }
        parsed = _validate_instance(provisional, index=index)
        if parsed["instance_id"] in seen:
            raise ScienceWorldOfficialError(
                "ScienceWorld roster input contains duplicate instance_id values"
            )
        seen.add(str(parsed["instance_id"]))
        env, observation, info = _stage_load_and_reset_instance(runtime, parsed)
        _safe_close(env)
        task_description = str(info.get("taskDesc") or "")
        initial_moves = _official_moves(
            info.get("moves"),
            environment_step_limit=int(parsed["max_steps"]),
            phase="reset",
        )
        staged.append(
            {
                "instance_id": parsed["instance_id"],
                "task_name": parsed["task_name"],
                "variation_idx": parsed["variation_idx"],
                "simplification_str": parsed["simplification_str"],
                "max_steps": parsed["max_steps"],
                "initial_moves": initial_moves,
                "task_description": task_description,
                "task_description_sha256": canonical_sha256(task_description),
                "initial_observation": observation,
                "initial_observation_sha256": canonical_sha256(observation),
            }
        )
    identity = environment_identity_payload(runtime, upstream_revision=revision)
    payload: dict[str, Any] = {
        "schema": SCIENCEWORLD_TASK_MANIFEST_SCHEMA,
        "upstream_repository": UPSTREAM_REPOSITORY,
        "upstream_revision": revision,
        "distribution_name": "scienceworld",
        "distribution_version": runtime.distribution_version,
        "environment_identity_sha256": canonical_sha256(identity),
        "split": "test",
        "instances": staged,
    }
    payload["artifact_sha256"] = canonical_sha256(payload)
    return payload


def stage_scienceworld_official(
    *,
    roster_path: str | Path,
    task_manifest_path: str | Path,
    candidate_lock_path: str | Path,
    upstream_revision: str,
    overwrite: bool = False,
) -> tuple[Path, Path]:
    """Stage a public selected-test manifest plus a non-authorizing candidate.

    The candidate is deliberately written outside the fixed lock path.  It is
    evidence for a human review, not an input that can promote an evaluation.
    """

    roster_file = Path(roster_path).expanduser().resolve()
    if not roster_file.is_file() or roster_file.is_symlink():
        raise ScienceWorldOfficialError(
            f"ScienceWorld roster input is missing or unsafe: {roster_file}"
        )
    manifest_file = Path(task_manifest_path).expanduser().resolve()
    candidate_file = Path(candidate_lock_path).expanduser().resolve()
    if candidate_file == repository_environment_lock_path().resolve():
        raise ScienceWorldOfficialError(
            "candidate_lock_path must not be the fixed reviewed environment lock path; review and commit manually"
        )
    _safe_relative_path(manifest_file, _REPOSITORY_ROOT, label="task_manifest_path")
    runtime = resolve_scienceworld_runtime()
    roster = _read_json_mapping(roster_file, label="ScienceWorld roster input")
    manifest = _manifest_from_roster(
        roster=roster,
        runtime=runtime,
        upstream_revision=upstream_revision,
    )
    _write_json(manifest_file, manifest, overwrite=overwrite)
    identity = environment_identity_payload(runtime, upstream_revision=upstream_revision)
    candidate: dict[str, Any] = {
        "schema": SCIENCEWORLD_ENVIRONMENT_LOCK_SCHEMA,
        "candidate_only": True,
        "review_status": "candidate",
        **identity,
        "environment_identity_sha256": canonical_sha256(identity),
        "task_manifest_relpath": _safe_relative_path(
            manifest_file, _REPOSITORY_ROOT, label="task manifest"
        ),
        "task_manifest_sha256": _sha256_file(manifest_file),
        "task_roster_sha256": canonical_sha256(manifest["instances"]),
        "split": "test",
        "review": {"reason": "candidate generated by lh-platform stage-scienceworld-official"},
    }
    candidate["artifact_sha256"] = canonical_sha256(candidate)
    _write_json(candidate_file, candidate, overwrite=overwrite)
    return manifest_file, candidate_file


@BENCHMARKS.register("scienceworld_official")
class ScienceWorldOfficialBenchmark(BenchmarkBase):
    """Direct official-API ScienceWorld adapter with a reviewed environment lock."""

    name = "scienceworld_official"
    required_action_contract = "scienceworld_text/v1"
    eval_validity = EVAL_SMOKE
    runtime_eval_validity_dynamic = True
    runtime_eval_validity_max = EVAL_REAL_NATIVE
    has_real_data = False
    supports_native_eval = False
    has_native_harness = False
    is_mock = True

    def __init__(self, task_manifest_path: str | Path | None = None) -> None:
        self.dataset_path = (
            Path(task_manifest_path).expanduser().resolve() if task_manifest_path else None
        )
        self.dataset_manifest_path = self.dataset_path
        self.dataset_manifest_sha256: str | None = None
        self.dataset_split: str | None = "test"
        self.dataset_revision: str | None = None
        self.dataset_source_verified = False
        self.dataset_source_verification_reason = "ScienceWorld task manifest was not checked"
        self.dataset_source_lock_sha256: str | None = None
        self.environment_fingerprint: str | None = None
        self.evaluator_version: str | None = None
        self.data_source = "scienceworld_official_manifest_missing"
        self._manifest: TaskManifest | None = None
        self._runtime: ScienceWorldRuntime | None = None
        self._verification: LockVerification | None = None
        self._active: dict[str, _ActiveTask] = {}
        self._results: dict[str, dict[str, Any]] = {}
        self._artifact_export_error: str | None = None
        self._artifact_receipt_path: Path | None = None
        self._run_artifacts_dir: Path | None = None
        self._admit_static_contract()

    def bind_run_artifacts(self, artifacts_dir: Path) -> None:
        """Bind the receipt destination before this adapter can go native."""

        raw_destination = Path(artifacts_dir).expanduser()
        if raw_destination.is_symlink():
            raise ScienceWorldOfficialError(
                "ScienceWorld run artifacts directory must not be a symlink"
            )
        destination = raw_destination.resolve()
        if self._run_artifacts_dir is not None and destination != self._run_artifacts_dir:
            raise ScienceWorldOfficialError(
                "ScienceWorld run artifacts directory changed during one evaluation"
            )
        self._run_artifacts_dir = destination

    def _downgrade(self, reason: str, *, validity: str = EVAL_UNVERIFIED_LOADER) -> None:
        self.eval_validity = validity
        self.supports_native_eval = False
        self.has_native_harness = False
        self.is_mock = True
        self.dataset_source_verified = False
        self.dataset_source_verification_reason = reason

    def _admit_static_contract(self) -> None:
        if self.dataset_path is None:
            self._downgrade("no ScienceWorld task manifest was configured", validity=EVAL_SMOKE)
            return
        try:
            manifest = load_scienceworld_task_manifest(self.dataset_path)
        except ScienceWorldOfficialError as error:
            self.data_source = "scienceworld_official_manifest_invalid"
            self._downgrade(str(error))
            return
        self._manifest = manifest
        self.dataset_path = manifest.path
        self.dataset_manifest_path = manifest.path
        self.dataset_manifest_sha256 = manifest.file_sha256
        self.dataset_revision = str(manifest.payload["upstream_revision"])
        self.data_source = "scienceworld_official_test_manifest"
        try:
            runtime = resolve_scienceworld_runtime()
            verification = verify_scienceworld_environment(manifest, runtime)
        except ScienceWorldOfficialError as error:
            self._downgrade(str(error))
            return
        self._runtime = runtime
        self._verification = verification
        self.evaluator_version = f"scienceworld:{runtime.distribution_version}"
        self.environment_fingerprint = canonical_sha256(
            environment_identity_payload(runtime, upstream_revision=self.dataset_revision)
        )
        self.dataset_source_lock_sha256 = verification.sha256
        if verification.status != "verified":
            self._downgrade(verification.reason)
            return
        self.has_real_data = True
        self.dataset_source_verified = True
        self.dataset_source_verification_reason = verification.reason
        # Fresh probes in load() are the final admission check.  Do not label
        # the class real_native merely because a lock was found on disk.
        self.eval_validity = EVAL_UNVERIFIED_LOADER
        self.is_mock = False

    def _probe_instance(self, instance: Mapping[str, Any]) -> None:
        if self._runtime is None:
            raise ScienceWorldOfficialError("official ScienceWorld runtime is unavailable")
        env, _observation, _info = _load_and_reset_instance(self._runtime, instance)
        _safe_close(env)

    @staticmethod
    def _task_from_instance(instance: Mapping[str, Any]) -> Task:
        instruction = (
            f"{instance['task_description'].strip()}\n\n"
            f"Initial observation:\n{instance['initial_observation'].strip()}"
        )
        return Task(
            task_id=str(instance["instance_id"]),
            domain=TaskDomain.SCIENCE,
            instruction=instruction,
            max_steps=_runner_action_budget(instance),
            metadata={
                "task_name": str(instance["task_name"]),
                "variation_idx": int(instance["variation_idx"]),
                "simplification_str": str(instance["simplification_str"]),
                "environment": "ScienceWorld",
                "dataset_split": "test",
                "environment_step_limit": int(instance["max_steps"]),
                "initial_environment_moves": int(instance["initial_moves"]),
                "runner_action_limit": _runner_action_budget(instance),
            },
        )

    def load(self, n: int = 3) -> list[Task]:
        if self._manifest is None or self._runtime is None or self._verification is None:
            return []
        if self._verification.status != "verified":
            return []
        if self._run_artifacts_dir is None:
            self._downgrade(
                "ScienceWorld official evaluation requires a Runner-bound run artifacts directory"
            )
            return []
        selected = self._manifest.instances[: max(0, int(n))]
        if not selected:
            self._downgrade("no ScienceWorld instances selected", validity=EVAL_SMOKE)
            return []
        try:
            for instance in selected:
                self._probe_instance(instance)
        except Exception as error:
            self._downgrade(
                f"official ScienceWorld pre-dispatch probe failed: {type(error).__name__}: {error}"
            )
            return []
        self.eval_validity = EVAL_REAL_NATIVE
        self.supports_native_eval = True
        self.has_native_harness = True
        self.is_mock = False
        return [self._task_from_instance(instance) for instance in selected]

    def _instance_for(self, task: Task) -> Mapping[str, Any]:
        if self._manifest is None:
            raise ScienceWorldOfficialError("ScienceWorld manifest is unavailable")
        for instance in self._manifest.instances:
            if instance["instance_id"] == task.task_id:
                return instance
        raise ScienceWorldOfficialError(
            f"task {task.task_id!r} is not present in the locked ScienceWorld manifest"
        )

    def _start_task(self, task: Task) -> _ActiveTask:
        if (
            self.eval_validity != EVAL_REAL_NATIVE
            or self._runtime is None
            or self._manifest is None
        ):
            raise ScienceWorldOfficialError("ScienceWorld official environment was not admitted")
        # The Java JAR is an executable evaluation dependency.  Recheck the
        # reviewed identity immediately before a task starts so a package
        # replacement after pre-dispatch probing cannot inherit real_native.
        verification = verify_scienceworld_environment(self._manifest, self._runtime)
        if verification.status != "verified":
            self._downgrade(verification.reason)
            raise ScienceWorldOfficialError(verification.reason)
        instance = self._instance_for(task)
        env, _observation, info = _load_and_reset_instance(self._runtime, instance)
        return _ActiveTask(
            env=env,
            instance=instance,
            last_score=_official_score(info.get("score")),
            last_reward=0,
            last_moves=_official_moves(
                info.get("moves"),
                environment_step_limit=int(instance["max_steps"]),
                phase="reset",
            ),
        )

    def _record_result(
        self,
        task_id: str,
        *,
        score: int,
        reward: int,
        moves: int,
        completed: bool,
        verified: bool,
        reason: str,
    ) -> None:
        self._results[task_id] = {
            "score": score,
            "reward": reward,
            "moves": moves,
            "completed": bool(completed),
            "verified": bool(verified),
            "success": bool(completed and score == 100),
            "reason": reason,
        }

    def _export_run_artifacts(self) -> None:
        """Snapshot the exact manifest and approved lock used by this run.

        The server manifest may live under an ignored data directory.  A path
        and hash alone do not let a later reviewer reconstruct the selected
        test roster, so a real-native run preserves byte-identical copies in
        its own artifact directory and binds them in a small receipt.
        """

        if self._manifest is None or self._runtime is None:
            raise ScienceWorldOfficialError(
                "cannot snapshot an unavailable ScienceWorld environment"
            )
        if self._run_artifacts_dir is None:
            raise ScienceWorldOfficialError(
                "cannot snapshot ScienceWorld without a bound run artifacts directory"
            )
        verification = verify_scienceworld_environment(self._manifest, self._runtime)
        if verification.status != "verified" or verification.payload is None:
            raise ScienceWorldOfficialError(
                f"cannot snapshot an unverified ScienceWorld environment: {verification.reason}"
            )
        artifacts_dir = self._run_artifacts_dir
        if artifacts_dir.is_symlink():
            raise ScienceWorldOfficialError(
                "ScienceWorld run artifacts directory must not be a symlink"
            )
        artifact_root = artifacts_dir / "scienceworld_official"
        if artifact_root.exists() and artifact_root.is_symlink():
            raise ScienceWorldOfficialError(
                "ScienceWorld artifact destination must not be a symlink"
            )
        artifact_root.mkdir(parents=True, exist_ok=True)
        manifest_snapshot = artifact_root / "task_manifest.v1.json"
        lock_snapshot = artifact_root / "environment_lock.v1.json"
        receipt_path = artifact_root / "run_receipt.v1.json"
        _write_bytes(
            manifest_snapshot,
            self._manifest.path.read_bytes(),
            overwrite=True,
        )
        _write_bytes(lock_snapshot, verification.path.read_bytes(), overwrite=True)
        if _sha256_file(manifest_snapshot) != self._manifest.file_sha256:
            raise ScienceWorldOfficialError("ScienceWorld manifest snapshot hash mismatch")
        snapshot_lock = _read_json_mapping(
            lock_snapshot, label="ScienceWorld environment lock snapshot"
        )
        if snapshot_lock.get("artifact_sha256") != verification.sha256:
            raise ScienceWorldOfficialError("ScienceWorld environment lock snapshot hash mismatch")
        receipt: dict[str, Any] = {
            "schema": SCIENCEWORLD_RUN_RECEIPT_SCHEMA,
            "upstream_repository": UPSTREAM_REPOSITORY,
            "upstream_revision": self.dataset_revision,
            "environment_identity_sha256": verification.payload["environment_identity_sha256"],
            "task_manifest_path": manifest_snapshot.name,
            "task_manifest_sha256": self._manifest.file_sha256,
            "environment_lock_path": lock_snapshot.name,
            "environment_lock_artifact_sha256": verification.sha256,
            "evaluator_version": self.evaluator_version,
            "results": {task_id: self._results[task_id] for task_id in sorted(self._results)},
        }
        receipt["artifact_sha256"] = canonical_sha256(receipt)
        _write_json(receipt_path, receipt, overwrite=True)
        self._artifact_receipt_path = receipt_path

    def step(self, task: Task, action: Action) -> Observation:
        try:
            active = self._active.get(task.task_id)
            if active is None:
                active = self._start_task(task)
                self._active[task.task_id] = active
            observation, reward, done, info = active.env.step(action.raw)
            if not isinstance(info, Mapping):
                raise ScienceWorldOfficialError(
                    "official ScienceWorld step did not return an info mapping"
                )
            # Task identity may never change while the agent acts.
            if str(info.get("taskName") or "") != str(active.instance["task_name"]):
                raise ScienceWorldOfficialError(
                    "official ScienceWorld step returned a different taskName"
                )
            if info.get("variationIdx") != active.instance["variation_idx"]:
                raise ScienceWorldOfficialError(
                    "official ScienceWorld step returned a different variationIdx"
                )
            if str(info.get("simplificationStr") or "") != str(
                active.instance["simplification_str"]
            ):
                raise ScienceWorldOfficialError(
                    "official ScienceWorld step returned a different simplificationStr"
                )
            if (
                canonical_sha256(str(info.get("taskDesc") or ""))
                != active.instance["task_description_sha256"]
            ):
                raise ScienceWorldOfficialError(
                    "official ScienceWorld step task description drifted from locked manifest"
                )
            score = _official_score(info.get("score"))
            moves = _official_moves(
                info.get("moves"),
                environment_step_limit=int(active.instance["max_steps"]),
                phase="step",
            )
            reward_value = int(info.get("reward", reward))
            active.last_score = score
            active.last_reward = reward_value
            active.last_moves = moves
            completed = bool(done)
            if completed:
                self._record_result(
                    task.task_id,
                    score=score,
                    reward=reward_value,
                    moves=moves,
                    completed=True,
                    verified=True,
                    reason="official ScienceWorld terminal transition",
                )
                _safe_close(active.env)
                self._active.pop(task.task_id, None)
            return Observation(
                content=str(observation),
                info={
                    "done": completed,
                    "success": bool(completed and score == 100),
                    "continue": not completed,
                    "score": score,
                    "reward": reward_value,
                    "moves": moves,
                    "environment": "ScienceWorld",
                },
            )
        except Exception as error:
            active = self._active.pop(task.task_id, None)
            if active is not None:
                _safe_close(active.env)
                self._record_result(
                    task.task_id,
                    score=active.last_score,
                    reward=active.last_reward,
                    moves=active.last_moves,
                    completed=False,
                    verified=False,
                    reason=f"official ScienceWorld runtime error: {type(error).__name__}: {error}",
                )
            else:
                self._record_result(
                    task.task_id,
                    score=0,
                    reward=0,
                    moves=0,
                    completed=False,
                    verified=False,
                    reason=f"official ScienceWorld task startup error: {type(error).__name__}: {error}",
                )
            return _observation_from_error(error)

    def close(self, artifacts_dir: Path | None = None) -> None:
        for task_id, active in list(self._active.items()):
            self._record_result(
                task_id,
                score=active.last_score,
                reward=active.last_reward,
                moves=active.last_moves,
                completed=False,
                # No official terminal transition occurred. A partial score
                # is diagnostic state only, never a verified failure sample.
                verified=False,
                reason="runner stopped before official ScienceWorld terminal transition",
            )
            _safe_close(active.env)
        self._active.clear()
        if artifacts_dir is not None:
            try:
                self.bind_run_artifacts(artifacts_dir)
            except Exception as error:
                self._artifact_export_error = (
                    "official ScienceWorld run artifact binding failed: "
                    f"{type(error).__name__}: {error}"
                )
                self._downgrade(self._artifact_export_error)
                return
        if self.eval_validity == EVAL_REAL_NATIVE:
            try:
                self._export_run_artifacts()
            except Exception as error:
                self._artifact_export_error = (
                    "official ScienceWorld run artifact export failed: "
                    f"{type(error).__name__}: {error}"
                )
                # A real-native result must carry the exact selected task set
                # and approved environment lock.  Without these artifacts it
                # is an unverified diagnostic, not a reproducible evaluation.
                self._downgrade(self._artifact_export_error)

    def finalize_run_evidence(
        self,
        *,
        run_id: str,
        trajectory_manifest: Mapping[str, Any],
    ) -> Mapping[str, Any]:
        """Bind this run's receipt to Runner's exact task trajectories.

        The initial receipt emitted by :meth:`close` deliberately contains no
        Runner implementation detail because the manifest does not exist yet.
        This second, fail-closed phase seals the relationship in both
        directions: the receipt names this run and trajectory manifest, while
        Runner later records the receipt's file SHA in its own contract.
        """

        if self.eval_validity != EVAL_REAL_NATIVE:
            # ``close`` may have downgraded after an artifact-export failure.
            # The generic contract already records that weaker validity; do
            # not invent a receipt descriptor for it.
            return {}
        if self._run_artifacts_dir is None or self._artifact_receipt_path is None:
            raise ScienceWorldOfficialError(
                "ScienceWorld real_native run is missing its bound receipt artifact"
            )
        if trajectory_manifest.get("schema") != RUNNER_TRAJECTORY_MANIFEST_SCHEMA:
            raise ScienceWorldOfficialError(
                "ScienceWorld received an invalid Runner trajectory manifest"
            )
        entries = trajectory_manifest.get("entries")
        if not isinstance(entries, list) or not entries:
            raise ScienceWorldOfficialError(
                "ScienceWorld trajectory manifest requires non-empty entries"
            )
        task_ids = [
            str(entry.get("task_id") or "") for entry in entries if isinstance(entry, Mapping)
        ]
        if (
            len(task_ids) != len(entries)
            or not all(task_ids)
            or len(set(task_ids)) != len(task_ids)
        ):
            raise ScienceWorldOfficialError(
                "ScienceWorld trajectory manifest has invalid task identities"
            )
        result_ids = set(self._results)
        if result_ids != set(task_ids):
            raise ScienceWorldOfficialError(
                "ScienceWorld receipt cannot bind a trajectory manifest whose tasks lack official results"
            )
        if any(
            not bool(result.get("completed")) or not bool(result.get("verified"))
            for result in self._results.values()
        ):
            raise ScienceWorldOfficialError(
                "ScienceWorld receipt cannot bind an interrupted or unverified environment episode"
            )
        receipt_path = self._artifact_receipt_path
        if receipt_path.is_symlink() or not receipt_path.is_file():
            raise ScienceWorldOfficialError("ScienceWorld run receipt is missing or unsafe")
        try:
            receipt_path.resolve().relative_to(self._run_artifacts_dir.resolve())
        except ValueError as error:
            raise ScienceWorldOfficialError(
                "ScienceWorld run receipt escaped the bound artifacts directory"
            ) from error
        receipt = _read_json_mapping(receipt_path, label="ScienceWorld run receipt")
        declared = _require_sha256(
            receipt.get("artifact_sha256"), label="ScienceWorld receipt artifact_sha256"
        )
        if declared != canonical_sha256(
            {key: value for key, value in receipt.items() if key != "artifact_sha256"}
        ):
            raise ScienceWorldOfficialError(
                "ScienceWorld run receipt artifact_sha256 mismatch before binding"
            )
        manifest_sha256 = canonical_sha256(trajectory_manifest)
        receipt["run_id"] = str(run_id)
        receipt["trajectory_manifest_schema"] = RUNNER_TRAJECTORY_MANIFEST_SCHEMA
        receipt["trajectory_manifest_sha256"] = manifest_sha256
        receipt["trajectory_task_ids"] = sorted(task_ids)
        receipt["artifact_sha256"] = canonical_sha256(
            {key: value for key, value in receipt.items() if key != "artifact_sha256"}
        )
        _write_json(receipt_path, receipt, overwrite=True)
        try:
            relative_path = receipt_path.resolve().relative_to(
                self._run_artifacts_dir.parent.resolve()
            )
        except ValueError as error:
            raise ScienceWorldOfficialError(
                "ScienceWorld receipt has no safe run-relative path"
            ) from error
        return {
            "receipts": [
                {
                    "name": "scienceworld_official_run_receipt",
                    "schema": SCIENCEWORLD_RUN_RECEIPT_SCHEMA,
                    "path": relative_path.as_posix(),
                    "sha256": _sha256_file(receipt_path),
                    "run_id": str(run_id),
                    "trajectory_manifest_sha256": manifest_sha256,
                }
            ]
        }

    def outcome_evidence(self, task: Task) -> OutcomeEvidence:
        if self._artifact_export_error is not None:
            return OutcomeEvidence(
                success=False,
                reason=self._artifact_export_error,
                evidence_quality=EVIDENCE_WEAK,
                source="scienceworld_official_api",
            )
        result = self._results.get(task.task_id)
        if result is None:
            return OutcomeEvidence(
                success=False,
                reason="no official ScienceWorld transition was recorded for task",
                evidence_quality=EVIDENCE_WEAK,
                source="scienceworld_official_api",
            )
        if not result["verified"]:
            return OutcomeEvidence(
                success=False,
                reason=str(result["reason"]),
                evidence_quality=EVIDENCE_WEAK,
                source="scienceworld_official_api",
                extra={"environment_score": result["score"]},
            )
        return OutcomeEvidence(
            success=bool(result["success"]),
            reason=str(result["reason"]),
            evidence_quality=EVIDENCE_STRONG,
            source="scienceworld_official_api",
            extra={
                "environment_score": result["score"],
                "environment_moves": result["moves"],
                "environment_completed": result["completed"],
            },
        )

    def task_metrics(self, task: Task, trajectory: Trajectory) -> dict[str, object]:
        del trajectory
        result = self._results.get(task.task_id)
        if result is None:
            return {}
        return {
            "environment_score": int(result["score"]),
            "environment_reward": int(result["reward"]),
            "environment_moves": int(result["moves"]),
            "environment_completed": int(bool(result["completed"])),
        }
