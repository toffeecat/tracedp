"""Fail-closed official ScienceWorld evaluation adapter.

``scienceworld.py`` remains a smoke fixture.  This adapter deliberately uses
the upstream :class:`scienceworld.ScienceWorldEnv` Python API directly and can
reach ``real_native`` only when all three independent facts agree:

1. a selected test-instance manifest was generated by the official API;
2. the installed Python module and JAR match a reviewed, HEAD-tracked lock;
3. a fresh official-environment probe reproduces every selected task's public
   description and initial observation before a model can be dispatched.

The staging command creates a *candidate* lock only.  It never self-authorizes
an environment; a maintainer must review the module/JAR hashes and commit an
approved replacement at the fixed repository path.
"""

